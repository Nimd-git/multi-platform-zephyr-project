'''Runner for flashing Atmosic ATM34xx via the openair fast_load protocol.

J-Link's FLM flow (loadfile/loadbin) cannot erase ATM34 RRAM: the J-Link
DLL calls SEGGER_FL_Prepare(Verify) once and then Erase() without a
Prepare(Erase), which the Atmosic FLM rejects. This runner bypasses the
FLM entirely by loading Atmosic's fast_load.bin into SRAM and driving its
shared-memory command-block protocol through J-Link Commander, mirroring
openocd/fast_load/atm_fast_load.tcl from the openair module.

Protocol summary (ATM34xx-5 / rev-5):
  1. loadbin fast_load.bin -> SRAM vector table base (0x20000000)
  2. PSEQ init (undo ROM benign-boot OVERRIDES)
  3. Set SP/PC via DCRDR/DCRSR and resume the fast_load reset handler
  4. Verify magic numbers at block info, read buf0 address
  5. fl_ram_init command block, then kick
  6. Erase command block (0xFFFF = erase all), then kick
  7. Program the image in 16 KiB chunks through buf0, kicking per chunk
  8. Start the flashed firmware via VTOR + SP/PC from its vector table

A no-op ResetTarget J-Link script is generated on the fly so that the
'loadbin' commands used for chunk data only write memory and never reset
the target (a reset would wipe the fast_load state from SRAM).
'''

import argparse
import re
import shutil
import struct
import subprocess
import sys
from pathlib import Path

from runners.core import FileType, RunnerCaps, ZephyrBinaryRunner

# fast_load protocol defaults for ATM34xx-5 (from openair
# modules/hal_atmosic/ATM34xx/rev-5/openocd/fast_load/atm_fast_load.cfg)
DEFAULT_BLOCK_INFO = 0x2001A37C      # shared memory: magic/version/buf addrs
DEFAULT_KICK_PROGRAM = 0x20002570    # opcode dispatcher entry (Thumb ORed)
DEFAULT_STACK_TOP = 0x20040000       # fast_load stack
DEFAULT_VECTOR_TABLE = 0x20000000    # fast_load image load base
DEFAULT_RESET_HANDLER = 0x200051D0   # fast_load reset handler (Thumb ORed)
DEFAULT_RRAM_BASE = 0x10000          # RRAM base in fast_load addressing
DEFAULT_CPU_BASE = 0x10010000        # RRAM base as seen by the CPU/debugger

FL_SECTOR_SIZE = 0x4000              # 16 KiB programming chunks
FL_OP_FW_LOAD = 0x01
FL_OP_ERASE = 0x02
FL_ERASE_ALL = 0xFFFF

FL_MAGIC0 = 0x5F445753
FL_MAGIC1 = 0x4F47454E

# Cortex-M33 debug registers (DCRDR/DCRSR register write)
DCRDR = 0xE000EDF8
DCRSR = 0xE000EDF4
DCRSR_WR = 0x00010000
REG_MSP = 0x09
REG_PC = 0x0F
VTOR = 0xE000ED08

# PSEQ init: undo what ROM benign boot did to the OVERRIDES register
PSEQ_INIT_CMDS = [
    (0x50153020, 0x1),   # enable pseq
    (0x40158050, 0x0),   # CMSDK_PSEQ_NONSECURE OVERRIDES reset value
    (0x50153020, 0x0),   # disable pseq
]

JLINK_SCRIPT_TEMPLATE = '''\
/*********************************************************************
* Auto-generated by the atmfastload west runner. Do not edit.
* InitTarget/SetupTarget mirror the Atmosic EVK J-Link script;
* ResetTarget is a no-op so Commander 'loadbin' never resets the target.
**********************************************************************/

int ConfigTargetSettings(void) {
    return 0;
}

U32 _aPINMode[8];
U32 _aPINState[8];

int InitTarget(void) {
    int i;
    int r;

    Report("atmfastload - InitTarget");
    i = 0;
    do {
        _aPINMode[i] = JLINK_PIN_OVERRIDE_MODE_RELEASE;
        i += 1;
    } while(i < JLINK_PIN_MAX_NUM_PINS);
    r = JLINK_PIN_Override(&_aPINMode[0], &_aPINState[0]);
    if (r < 0) {
        return r;
    }

    _aPINMode[1] = JLINK_PIN_OVERRIDE_MODE_PIO_OUT_HIGH;
    _aPINMode[4] = JLINK_PIN_OVERRIDE_MODE_PIO_OUT_HIGH;
    _aPINMode[5] = JLINK_PIN_OVERRIDE_MODE_PIO_OUT_HIGH;
    r = JLINK_PIN_Override(&_aPINMode[0], &_aPINState[0]);
    if (r < 0) {
        return r;
    }
    JLINK_SYS_Sleep(500);

    _aPINMode[4] = JLINK_PIN_OVERRIDE_MODE_PIO_OUT_LOW;
    _aPINMode[5] = JLINK_PIN_OVERRIDE_MODE_PIO_OUT_LOW;
    r = JLINK_PIN_Override(&_aPINMode[0], &_aPINState[0]);
    if (r < 0) {
        return r;
    }
    JLINK_SYS_Sleep(500);

    _aPINMode[1] = JLINK_PIN_OVERRIDE_MODE_PIO_OUT_LOW;
    r = JLINK_PIN_Override(&_aPINMode[0], &_aPINState[0]);
    if (r < 0) {
        return r;
    }

    i = 0;
    do {
        _aPINMode[i] = JLINK_PIN_OVERRIDE_MODE_RELEASE;
        i += 1;
    } while(i < JLINK_PIN_MAX_NUM_PINS);
    JLINK_PIN_Override(&_aPINMode[0], &_aPINState[0]);
    return 0;
}

int SetupTarget(void) {
    int r;

    r = JLINK_MEM_WriteU32(0x50153020, 0x1);
    if (r < 0) {
        return r;
    }
    r = JLINK_MEM_WriteU32(0x40158050, 0x0);
    if (r < 0) {
        return r;
    }
    r = JLINK_MEM_WriteU32(0x50153020, 0x0);
    if (r < 0) {
        return r;
    }
    return 0;
}

int ResetTarget(void) {
    Report("atmfastload ResetTarget: no-op");
    return 0;
}
'''


def _u32(value):
    return f'0x{value:08X}'


def _find_jlink():
    '''Locate J-Link Commander (JLink.exe) on Windows.'''
    if sys.platform == 'win32':
        try:
            import winreg
            key = winreg.OpenKeyEx(winreg.HKEY_CURRENT_USER,
                                   r'Software\SEGGER\J-Link')
            exe = Path(winreg.QueryValueEx(key, 'InstallPath')[0]) / 'JLink.exe'
            if exe.is_file():
                return str(exe)
        except Exception:
            pass
        # Fall back to the newest SEGGER installation under Program Files.
        candidates = sorted(
            Path(r'C:\Program Files\SEGGER').glob('JLink*/JLink.exe'))
        if candidates:
            return str(candidates[-1])
    exe = shutil.which('JLink.exe' if sys.platform == 'win32' else 'JLinkExe')
    if exe:
        return exe
    raise RuntimeError('JLink.exe not found; pass --jlink=<path to JLink.exe>')


class AtmFastloadRunner(ZephyrBinaryRunner):
    '''Runner front-end for the Atmosic fast_load J-Link flashing flow.'''

    def __init__(self, cfg, device, fast_load_bin, jlink=None,
                 block_info=DEFAULT_BLOCK_INFO,
                 kick_program=DEFAULT_KICK_PROGRAM,
                 stack_top=DEFAULT_STACK_TOP,
                 vector_table=DEFAULT_VECTOR_TABLE,
                 reset_handler=DEFAULT_RESET_HANDLER,
                 rram_base=DEFAULT_RRAM_BASE,
                 cpu_base=DEFAULT_CPU_BASE,
                 erase_wait_ms=8000, prog_wait_ms=500):
        super().__init__(cfg)
        self.device = device
        self.jlink = jlink
        self.fast_load_bin = Path(fast_load_bin)
        self.block_info = block_info
        self.kick_program = kick_program
        self.stack_top = stack_top
        self.vector_table = vector_table
        self.reset_handler = reset_handler
        self.rram_base = rram_base
        self.cpu_base = cpu_base
        self.erase_wait_ms = erase_wait_ms
        self.prog_wait_ms = prog_wait_ms

    @classmethod
    def name(cls):
        return 'atmfastload'

    @classmethod
    def capabilities(cls):
        return RunnerCaps(commands={'flash'}, file=FileType.BIN)

    @classmethod
    def do_add_parser(cls, parser: argparse.ArgumentParser):
        parser.add_argument('--device', default='ATM3405-WQK',
                            help='J-Link device name (default: ATM3405-WQK)')
        parser.add_argument('--jlink',
                            help='path to JLink.exe (default: auto-detect)')
        parser.add_argument('--fast-load-bin', required=True,
                            help='path to the Atmosic fast_load.bin image')
        parser.add_argument('--block-info', type=lambda x: int(x, 0),
                            default=DEFAULT_BLOCK_INFO,
                            help='fast_load shared-memory block info address')
        parser.add_argument('--kick-program', type=lambda x: int(x, 0),
                            default=DEFAULT_KICK_PROGRAM,
                            help='fast_load kick program address')
        parser.add_argument('--stack-top', type=lambda x: int(x, 0),
                            default=DEFAULT_STACK_TOP,
                            help='fast_load stack top address')
        parser.add_argument('--vector-table', type=lambda x: int(x, 0),
                            default=DEFAULT_VECTOR_TABLE,
                            help='fast_load image load base in SRAM')
        parser.add_argument('--reset-handler', type=lambda x: int(x, 0),
                            default=DEFAULT_RESET_HANDLER,
                            help='fast_load reset handler address')
        parser.add_argument('--rram-base', type=lambda x: int(x, 0),
                            default=DEFAULT_RRAM_BASE,
                            help='RRAM base address in fast_load addressing')
        parser.add_argument('--cpu-base', type=lambda x: int(x, 0),
                            default=DEFAULT_CPU_BASE,
                            help='RRAM base address as seen by the CPU')
        parser.add_argument('--erase-wait-ms', type=int, default=8000,
                            help='wait time after a full RRAM erase kick')
        parser.add_argument('--prog-wait-ms', type=int, default=500,
                            help='wait time after each 16 KiB program kick')

    @classmethod
    def do_create(cls, cfg, args):
        return cls(cfg, args.device, args.fast_load_bin,
                   jlink=args.jlink,
                   block_info=args.block_info,
                   kick_program=args.kick_program,
                   stack_top=args.stack_top,
                   vector_table=args.vector_table,
                   reset_handler=args.reset_handler,
                   rram_base=args.rram_base,
                   cpu_base=args.cpu_base,
                   erase_wait_ms=args.erase_wait_ms,
                   prog_wait_ms=args.prog_wait_ms)

    def _kick(self, lines, wait_ms):
        '''Append a fast_load kick sequence: run the kick program briefly.'''
        lines += [
            f'w4 {_u32(DCRDR)}, {_u32(self.stack_top)}',
            f'w4 {_u32(DCRSR)}, {_u32(DCRSR_WR | REG_MSP)}',
            f'w4 {_u32(DCRDR)}, {_u32(self.kick_program | 1)}',
            f'w4 {_u32(DCRSR)}, {_u32(DCRSR_WR | REG_PC)}',
            'g',
            f'sleep {wait_ms}',
            'h',
            # Owner byte must read back 0 (fast_load finished the command).
            f'mem32 {_u32(self.buf0)}, 1',
        ]

    def _cmd_block(self, lines, opcode, size, addr):
        '''Append command block writes: owner=1, opcode, size(LE16), addr.'''
        word0 = 1 | (opcode << 8) | ((size & 0xFFFF) << 16)
        lines.append(f'w4 {_u32(self.buf0)}, {_u32(word0)}')
        lines.append(f'w4 {_u32(self.buf0 + 4)}, {_u32(addr)}')

    def _commander_script(self, chunk_paths, image, sp, pc):
        '''Build the full J-Link Commander script for the flash flow.'''
        L = []
        L += ['si SWD', 'speed 100', 'connect', 'halt', 'speed 2000']

        # Phase 1: load fast_load into SRAM and start its reset handler.
        L.append(f'loadbin {self.fast_load_bin}, {_u32(self.vector_table)}')
        for reg, val in PSEQ_INIT_CMDS:
            L.append(f'w4 {_u32(reg)}, {_u32(val)}')
        L += [
            f'w4 {_u32(DCRDR)}, {_u32(self.stack_top)}',
            f'w4 {_u32(DCRSR)}, {_u32(DCRSR_WR | REG_MSP)}',
            'sleep 10',
            f'w4 {_u32(DCRDR)}, {_u32(self.reset_handler | 1)}',
            f'w4 {_u32(DCRSR)}, {_u32(DCRSR_WR | REG_PC)}',
            'sleep 10',
            'g',
            'sleep 500',
            'h',
        ]

        # Phase 2: check magic and read buf0 (verified from the log later).
        L.append(f'mem32 {_u32(self.block_info)}, 4')
        L.append(f'mem32 {_u32(self.block_info + 16)}, 1')

        # Phase 3: fl_ram_init (owner=1, opcode=1, size=0, addr=0).
        self._cmd_block(L, FL_OP_FW_LOAD, 0, 0)
        self._kick(L, 300)

        # Phase 4: erase entire RRAM.
        self._cmd_block(L, FL_OP_ERASE, FL_ERASE_ALL, self.rram_base)
        self._kick(L, self.erase_wait_ms)

        # Phase 5: program chunks.
        offset = 0
        for chunk in chunk_paths:
            size = chunk.stat().st_size
            L.append(f'loadbin {chunk}, {_u32(self.buf0 + 8)}')
            self._cmd_block(L, FL_OP_FW_LOAD, size, self.rram_base + offset)
            self._kick(L, self.prog_wait_ms)
            offset += size

        # Phase 6: verify the first words of the image (checked in python).
        L.append(f'mem32 {_u32(self.cpu_base)}, 4')

        # Phase 7: start the firmware from its own vector table.
        L += [
            f'w4 {_u32(VTOR)}, {_u32(self.cpu_base)}',
            f'w4 {_u32(DCRDR)}, {_u32(sp)}',
            f'w4 {_u32(DCRSR)}, {_u32(DCRSR_WR | REG_MSP)}',
            f'w4 {_u32(DCRDR)}, {_u32(pc)}',
            f'w4 {_u32(DCRSR)}, {_u32(DCRSR_WR | REG_PC)}',
            'g',
            'q',
        ]
        return L

    @property
    def buf0(self):
        '''fast_load command/data buffer; layout from block info + 16.'''
        # The actual address is read from the target at runtime; for the
        # ATM34xx-5 rev-5 fast_load build it is always 0x2001A638. It is
        # derived from block_info and kept as a property so the commander
        # script generation stays readable.
        return self._buf0

    def do_run(self, command, **kwargs):
        if command != 'flash':
            raise RuntimeError(f'atmfastload does not support "{command}"')

        bin_file = Path(self.cfg.bin_file)
        if not bin_file.is_file():
            raise RuntimeError(f'no binary file found: {bin_file}')
        image = bin_file.read_bytes()
        if len(image) < 8:
            raise RuntimeError(f'binary too small: {bin_file}')
        sp, pc = struct.unpack_from('<II', image, 0)

        if not self.fast_load_bin.is_file():
            raise RuntimeError(f'fast_load.bin not found: {self.fast_load_bin}')

        # The rev-5 fast_load build keeps buf0 at block_info + 0x2BC
        # (0x2001A37C + 0x2BC = 0x2001A638, confirmed by the runtime read
        # of block_info+16 during the EVK flashing session).
        self._buf0 = self.block_info + 0x2BC

        jlink = self.jlink or _find_jlink()
        work_dir = Path(self.cfg.build_dir) / 'atmfastload'
        work_dir.mkdir(parents=True, exist_ok=True)

        # Split the image into 16 KiB chunks for the fast_load buffer.
        chunk_paths = []
        for idx in range(0, len(image), FL_SECTOR_SIZE):
            chunk = work_dir / f'chunk_{idx // FL_SECTOR_SIZE}.bin'
            chunk.write_bytes(image[idx:idx + FL_SECTOR_SIZE])
            chunk_paths.append(chunk)

        script_file = work_dir / 'atmfastload.JLinkScript'
        script_file.write_text(JLINK_SCRIPT_TEMPLATE, encoding='utf-8')

        cmd_file = work_dir / 'atmfastload.jlink'
        lines = self._commander_script(chunk_paths, image, sp, pc)
        cmd_file.write_text('\n'.join(lines) + '\n', encoding='ascii')

        cmd = [
            jlink,
            '-device', self.device,
            '-if', 'SWD',
            '-speed', '100',
            '-NoGui', '1',
            '-ExitOnError', '1',
            '-JLinkScriptFile', str(script_file),
            '-CommandFile', str(cmd_file),
        ]
        self.logger.info(' '.join(str(c) for c in cmd))
        proc = subprocess.run(cmd, capture_output=True, text=True,
                              errors='replace')
        out = proc.stdout or ''
        for line in out.splitlines():
            self.logger.info(line)
        if proc.stderr:
            for line in proc.stderr.splitlines():
                self.logger.warning(line)
        if proc.returncode != 0:
            raise RuntimeError(
                f'J-Link Commander failed (exit {proc.returncode}); '
                f'see output above (script: {cmd_file})')

        self._check_magic(out)
        self._check_verify(out, image)

        self.logger.info(
            f'Flashed {len(image)} bytes to RRAM at {_u32(self.cpu_base)} '
            f'and started firmware (SP={_u32(sp)}, PC={_u32(pc)}).')

    def _check_magic(self, out):
        '''Verify fast_load reported the expected magic numbers.'''
        m = re.search(rf'{self.block_info:08X} = ([0-9A-F]{{8}}) '
                      r'([0-9A-F]{8})', out)
        if not m:
            raise RuntimeError('fast_load magic numbers not read back; '
                               'reset handler did not run (see log above)')
        magic0, magic1 = int(m.group(1), 16), int(m.group(2), 16)
        if (magic0, magic1) != (FL_MAGIC0, FL_MAGIC1):
            raise RuntimeError(
                f'fast_load magic mismatch: {_u32(magic0)} {_u32(magic1)} '
                f'(expected {_u32(FL_MAGIC0)} {_u32(FL_MAGIC1)})')

    def _check_verify(self, out, image):
        '''Compare the first 16 bytes read back from RRAM with the image.'''
        m = re.search(rf'{self.cpu_base:08X} = '
                      r'((?:[0-9A-F]{8} ?){4})', out)
        if not m:
            raise RuntimeError('RRAM verify read not found in J-Link output')
        words = [int(w, 16) for w in m.group(1).split()]
        expected = struct.unpack_from('<IIII', image, 0)
        if words != list(expected):
            raise RuntimeError(
                'RRAM verify mismatch at '
                f'{_u32(self.cpu_base)}: got '
                + ' '.join(_u32(w) for w in words)
                + ', expected '
                + ' '.join(_u32(w) for w in expected))
